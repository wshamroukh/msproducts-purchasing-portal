import { getConfig } from './config';
import { getAuthHeaders } from './auth';

export class ApiError extends Error {
  constructor(message, status) {
    super(message);
    this.status = status;
  }
}

export async function api(path, { method = 'GET', body } = {}) {
  const headers = { ...(await getAuthHeaders()) };
  if (body !== undefined) headers['Content-Type'] = 'application/json';

  let res;
  try {
    res = await fetch(`${getConfig().apiBaseUrl.replace(/\/$/, '')}${path}`, {
      method,
      headers,
      body: body !== undefined ? JSON.stringify(body) : undefined,
    });
  } catch {
    throw new ApiError('Cannot reach the API. Check that the backend is running and CORS allows this site.', 0);
  }

  const text = await res.text();
  let data = null;
  try { data = text ? JSON.parse(text) : null; } catch { data = { error: text }; }
  if (!res.ok) throw new ApiError((data && data.error) || `Request failed (${res.status})`, res.status);
  return data;
}

/**
 * Downloads an order PDF. The API answers 202 while the PDF is still being generated by the
 * Function App, so this polls for up to ~40 seconds. onWaiting() is called while it waits.
 */
export async function downloadPdf(path, filename, { onWaiting } = {}) {
  const url = `${getConfig().apiBaseUrl.replace(/\/$/, '')}${path}`;
  for (let attempt = 0; attempt < 20; attempt++) {
    let res;
    try {
      res = await fetch(url, { headers: await getAuthHeaders() });
    } catch {
      throw new ApiError('Cannot reach the API to download the PDF.', 0);
    }
    if (res.status === 202) {
      if (onWaiting) onWaiting();
      const wait = Math.min(Number(res.headers.get('Retry-After')) || 2, 5) * 1000;
      await new Promise((r) => setTimeout(r, wait));
      continue;
    }
    if (!res.ok) {
      let message = `Download failed (${res.status})`;
      try { message = (await res.json()).error || message; } catch { /* not JSON */ }
      throw new ApiError(message, res.status);
    }
    const blobUrl = URL.createObjectURL(await res.blob());
    const a = document.createElement('a');
    a.href = blobUrl;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    a.remove();
    setTimeout(() => URL.revokeObjectURL(blobUrl), 60000);
    return;
  }
  throw new ApiError('The PDF is taking longer than usual to generate. Please try again in a minute.', 504);
}
